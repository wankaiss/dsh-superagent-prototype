/**
 * Every app-authored, user-facing string of the console: labels, accessible names, empty states, confirmations and
 * notification templates. API content (titles, messages, record text) stays data and never comes from here.
 *
 * Code label tables (reasons, health parts, stages, outcomes, settings changes) mirror the English strings of the
 * in-DSH panel (src/client/locales.ts) and src/core/reasons.ts. They are copied, not imported, because those modules
 * are host runtime code; an unknown code falls back to the raw code.
 */

const fill = (template: string, values: Record<string, string | number | undefined> = {}) =>
  template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values[name]
    return value === undefined || value === '' ? match : String(value)
  })
